CREATE TABLE tourist_spots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL CHECK (length(trim(name)) > 0),
    description VARCHAR(2000),
    latitude NUMERIC(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    radius_meters INTEGER NOT NULL CHECK (radius_meters > 0),
    address VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE waste_reports ADD COLUMN tourist_spot_id BIGINT;
ALTER TABLE waste_reports ADD CONSTRAINT reports_tourist_spot_fk
    FOREIGN KEY (tourist_spot_id) REFERENCES tourist_spots(id);

CREATE INDEX tourist_spots_active_name_idx ON tourist_spots(name, id) WHERE active;
CREATE INDEX reports_tourist_spot_status_idx ON waste_reports(tourist_spot_id, current_status);
