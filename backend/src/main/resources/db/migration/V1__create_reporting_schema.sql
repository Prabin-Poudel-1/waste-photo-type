CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255),
 phone VARCHAR(32),
 role VARCHAR(20) NOT NULL CHECK (role IN ('USER','DEPARTMENT','ADMIN')),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT normalized_email CHECK (email = lower(email)),
 CONSTRAINT password_hash_format CHECK (
   password_hash IS NULL
   OR password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'
 )
);

CREATE TABLE departments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(150) NOT NULL UNIQUE,
 description VARCHAR(1000),
 contact_email VARCHAR(254),
 contact_phone VARCHAR(32),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE waste_categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(60) NOT NULL UNIQUE,
 name VARCHAR(100) NOT NULL UNIQUE,
 description VARCHAR(500),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE waste_reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporter_id BIGINT REFERENCES app_users(id),
 description VARCHAR(2000),
 latitude NUMERIC(9,6) NOT NULL CHECK (
   latitude BETWEEN -90 AND 90
 ),
 longitude NUMERIC(9,6) NOT NULL CHECK (
   longitude BETWEEN -180 AND 180
 ),
 address VARCHAR(500),
 severity VARCHAR(20) NOT NULL CHECK (
   severity IN ('LOW','MEDIUM','HIGH','CRITICAL')
 ),
 current_status VARCHAR(30) NOT NULL CHECK (
   current_status IN (
     'SUBMITTED',
     'AI_ANALYZED',
     'PENDING_VERIFICATION',
     'VERIFIED',
     'ASSIGNED',
     'IN_PROGRESS',
     'RESOLVED',
     'REJECTED'
   )
 ),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE waste_detections (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id BIGINT NOT NULL REFERENCES waste_reports(id),
 waste_category_id BIGINT NOT NULL REFERENCES waste_categories(id),
 detected_label VARCHAR(100) NOT NULL,
 confidence NUMERIC(7,6) NOT NULL CHECK (
   confidence BETWEEN 0 AND 1
 ),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE report_images (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id BIGINT NOT NULL REFERENCES waste_reports(id),
 image_type VARCHAR(30) NOT NULL CHECK (
   image_type IN ('ORIGINAL','AFTER_CLEANUP','EVIDENCE')
 ),
 storage_key VARCHAR(500) NOT NULL UNIQUE,
 original_filename VARCHAR(255) NOT NULL,
 content_type VARCHAR(100) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE report_status_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id BIGINT NOT NULL REFERENCES waste_reports(id),
 status VARCHAR(30) NOT NULL CHECK (
   status IN (
     'SUBMITTED',
     'AI_ANALYZED',
     'PENDING_VERIFICATION',
     'VERIFIED',
     'ASSIGNED',
     'IN_PROGRESS',
     'RESOLVED',
     'REJECTED'
   )
 ),
 changed_by_id BIGINT REFERENCES app_users(id),
 note VARCHAR(1000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE report_assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id BIGINT NOT NULL REFERENCES waste_reports(id),
 department_id BIGINT NOT NULL REFERENCES departments(id),
 assigned_by_id BIGINT REFERENCES app_users(id),
 assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX one_active_assignment_per_report
 ON report_assignments(report_id)
 WHERE active;

CREATE TABLE routing_rules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 waste_category_id BIGINT REFERENCES waste_categories(id),
 department_id BIGINT NOT NULL REFERENCES departments(id),
 area_identifier VARCHAR(120),
 priority INTEGER NOT NULL DEFAULT 0 CHECK (priority >= 0),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT routing_criterion CHECK (
   waste_category_id IS NOT NULL
   OR nullif(trim(area_identifier),'') IS NOT NULL
 )
);

CREATE INDEX reports_created_idx
 ON waste_reports(created_at DESC, id DESC);

CREATE INDEX reports_status_created_idx
 ON waste_reports(current_status, created_at DESC);

CREATE INDEX reports_reporter_idx
 ON waste_reports(reporter_id);

CREATE INDEX reports_severity_idx
 ON waste_reports(severity);

CREATE INDEX detections_report_idx
 ON waste_detections(report_id);

CREATE INDEX detections_category_idx
 ON waste_detections(waste_category_id);

CREATE INDEX images_report_idx
 ON report_images(report_id);

CREATE INDEX history_report_time_idx
 ON report_status_history(report_id, created_at, id);

CREATE INDEX assignments_report_idx
 ON report_assignments(report_id);

CREATE INDEX assignments_department_idx
 ON report_assignments(department_id, active);

CREATE INDEX routing_category_area_idx
 ON routing_rules(waste_category_id, area_identifier, priority)
 WHERE active;

CREATE INDEX routing_department_idx
 ON routing_rules(department_id);